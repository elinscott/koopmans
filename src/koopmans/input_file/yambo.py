    @field_validator("BSEprop")
    @classmethod
    def check_bseprop_spectra(cls, value: str | None) -> str | None:
        """Require every name in ``BSEprop`` to be a spectrum yambo computes."""
        known = {"abs", "jdos", "kerr", "asymm", "anHAll", "magn", "dich", "photolum", "esrt"}
        unknown = set(value.split()) - known if value else set()
        if unknown:
            raise ValueError(
                f"`calculator_parameters.yambo.BSEprop` names {sorted(unknown)}; "
                f"choose from {sorted(known)}."
            )
        return value

    @model_validator(mode="after")
    def default_bsengblk_to_ngsblkxs(self) -> Self:
        """Default ``BSENGBlk`` to ``NGsBlkXs`` when the caller leaves it unset."""
        if self.BSENGBlk is None:
            self.BSENGBlk = self.NGsBlkXs
        return self

    @model_validator(mode="after")
    def check_bands_ordered(self) -> Self:
        """Require ``BSEBands`` to name an ascending, positive range."""
        first, last = self.BSEBands
        if first < 1 or last < first:
            raise ValueError(
                f"`calculator_parameters.yambo.BSEBands` = [{first}, {last}] must be a "
                "positive, ascending [first, last] band range."
            )
        return self

    @model_validator(mode="after")
    def check_energy_range_ordered(self) -> Self:
        """Require ``BEnRange`` to name an ascending window."""
        low, high = self.BEnRange
        if not low < high:
            raise ValueError(
                f"`calculator_parameters.yambo.BEnRange` = [{low}, {high}] must be "
                "ascending: the minimum energy must be strictly less than the maximum."
            )
        return self

    @model_validator(mode="after")
    def check_broadening_positive(self) -> Self:
        """Require both ``BDmRange`` values to be positive."""
        if any(value <= 0 for value in self.BDmRange):
            raise ValueError(
                f"`calculator_parameters.yambo.BDmRange` = {list(self.BDmRange)} must be positive."
            )
        return self

    def to_runcard_variables(self) -> dict[str, Any]:
        """Return this block's valued fields as a yambo runcard ``variables`` mapping.

        Each field's unit travels on its own ``Field(json_schema_extra={"unit": ...})``:
        a tuple field becomes ``[list(value), unit]``, a numeric scalar
        ``[value, unit]``, and a string field its bare string (yambopy renders
        a ``[value, unit]`` pair as an array block, which yambo ignores for a
        string variable). Optional fields left at ``None`` and flag fields (see
        :meth:`to_runcard_arguments`) are skipped.
        """
        variables: dict[str, Any] = {}
        for name, field in type(self).model_fields.items():
            value = getattr(self, name)
            if value is None or isinstance(value, bool):
                continue
            if isinstance(value, str):
                variables[name] = value
                continue
            if isinstance(value, tuple):
                value = list(value)
            unit = field.json_schema_extra["unit"]  # type: ignore[index]
            variables[name] = [value, unit]
        return variables

    def to_runcard_arguments(self) -> list[str]:
        """Return the names of this block's flag fields that are set, as runcard ``arguments``."""
        return [name for name in type(self).model_fields if getattr(self, name) is True]
